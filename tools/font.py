CHAR_WIDTH = 6  # 5 px glyph + 1 px shadow; all glyphs share it (fixed pitch, compact HUD)


def glyph_canvas(ch):
    c = Canvas(8, 8)
    key = ch.upper() if ch.isalpha() else ch
    rows = GLYPHS.get(key, "..... ..... ..... ..... ..... ..... .....").split()
    for y, row in enumerate(rows):
        for x, v in enumerate(row):
            if v == '#':
                c.set(x + 1, y + 1, 1)   # shadow first
    for y, row in enumerate(rows):
        for x, v in enumerate(row):
            if v == '#':
                c.set(x, y, 2 if y < 4 else 3 if y == 6 else 2)
    return c


def font_sheet():
    frames = [glyph_canvas(chr(code)) for code in range(ord('!'), ord('!') + 94)]
    return vstack(frames)


def glyph_rows(ch):
    return GLYPHS[ch].split()
