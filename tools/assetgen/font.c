const char* const* font_rows(char ch)
{
    for(size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i)
    {
        if(glyphs[i].ch == ch)
        {
            return glyphs[i].rows;
        }
    }

    return NULL;
}

canvas* font_glyph(char ch)
{
    canvas* c = canvas_new(8, 8);
    char key = isalpha((unsigned char) ch) ? (char) toupper((unsigned char) ch) : ch;
    const char* const* rows = font_rows(key);

    if(! rows)
    {
        return c;
    }

    for(int y = 0; y < 7; ++y)
    {
        for(int x = 0; x < 5; ++x)
        {
            if(rows[y][x] == '#')
            {
                canvas_set(c, x + 1, y + 1, 1);     /* shadow first */
            }
        }
    }

    for(int y = 0; y < 7; ++y)
    {
        for(int x = 0; x < 5; ++x)
        {
            if(rows[y][x] == '#')
            {
                canvas_set(c, x, y, y == 6 ? 3 : 2);
            }
        }
    }

    return c;
}
